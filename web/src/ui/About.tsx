// The About tab: what the tool is, who made it, where its code is, and credit for every data
// source, service, library, and tool it uses. The lists are in credits.ts.
// Written with Claude Code (Anthropic) assistance.
import { Fragment, type ReactNode } from "react";
import { DATA_CREDIT, useStore } from "../core";
import { ACKNOWLEDGMENTS, CHALLENGE, CODE, DOCS, NASA_DATA, PARTNER_DATA, REPO, SI_TOOL, TEAM, type Credit, type CreditLink } from "./credits";
import "./styles/about.css";

/** A link that opens in a new tab, so the view being studied stays open. */
function Out({ href, children }: { href: string; children: ReactNode }) {
  return (
    <a href={href} target="_blank" rel="noreferrer">
      {children}
    </a>
  );
}

/** Linked names in a row: "A", "A and B", or "A, B, and C". */
function Names({ links }: { links: CreditLink[] }) {
  return (
    <>
      {links.map((link, index) => (
        <Fragment key={link.url}>
          {index > 0 && (index === links.length - 1 ? (links.length > 2 ? ", and " : " and ") : ", ")}
          <Out href={link.url}>{link.name}</Out>
        </Fragment>
      ))}
    </>
  );
}

/** One list of credits, one to a line: the linked names, then what the tool uses them for. */
function Credits({ items }: { items: Credit[] }) {
  return (
    <ul className="credits">
      {items.map((item) => (
        <li key={item.links[0].name}>
          <Names links={item.links} />
          <span className="muted">. {item.use}</span>
        </li>
      ))}
    </ul>
  );
}

export function About() {
  const archive = useStore((s) => s.meta?.index);
  return (
    <div className="tool about">
      <p className="about-lead">
        <strong>SPHERExplorer</strong> plays every public SPHEREx image of a sky position in time order. It measures which sources moved, brightened, or
        faded between visits, and it reads the spectrum of any point across the 102 infrared bands.
      </p>
      <div className="about-grid">
        <section>
          <h2>The team</h2>
          <p>
            Team Turing Complete: <Names links={TEAM} />. Built for the NASA Space Apps Challenge 2026, challenge{" "}
            <Out href={CHALLENGE}>Planet X and SPHEREx</Out>.
          </p>
          <p>
            <strong>Not a NASA product.</strong> This is an independent team project. It is not an official NASA product and is not endorsed by NASA.
          </p>
        </section>
        <section>
          <h2>Source code and methods</h2>
          <p>
            The code is open source under the Apache License 2.0. It is on GitHub at <Out href={REPO}>github.com/mattsaund/SPHERExplorer</Out>.
          </p>
          <ul className="credits">
            <li>
              <Out href={DOCS.methods}>How each result is computed and checked</Out>
            </li>
            <li>
              <Out href={DOCS.embedding}>Link to a view, or embed it in your page</Out>
            </li>
            <li>
              <Out href={DOCS.references}>Every reference, license, and acknowledgment</Out>
            </li>
          </ul>
        </section>
        <section>
          <h2>Use of SI</h2>
          <p>
            The team set the idea, the features, and the direction. The code, the tests, and the documentation were written with{" "}
            <Out href={SI_TOOL.url}>{SI_TOOL.name}</Out> (Anthropic), a Super Intelligence (SI) tool, and are <Out href={DOCS.si}>labeled as SI work</Out>.
            No picture in the tool is generated by SI. Every image is drawn from the archives' data.
          </p>
        </section>
      </div>
      <div className="about-grid">
        <section>
          <h2>Data from NASA</h2>
          <p>
            {DATA_CREDIT.replace(/^Data: /, "")}.
            {archive &&
              ` ${archive.exposures.toLocaleString("en-US")} exposures are indexed, from releases ${archive.releases.map((release) => release.toUpperCase()).join(" and ")}. New exposures are added twice a week.`}
          </p>
          <Credits items={NASA_DATA} />
        </section>
        <section>
          <h2>Data from partner agencies and other sources</h2>
          <Credits items={PARTNER_DATA} />
        </section>
        <section>
          <h2>Code and tools</h2>
          <Credits items={CODE} />
        </section>
      </div>
      <section className="about-notes">
        <h2>Acknowledgments</h2>
        {ACKNOWLEDGMENTS.map((text) => (
          <p key={text} className="muted">
            {text}
          </p>
        ))}
      </section>
    </div>
  );
}
